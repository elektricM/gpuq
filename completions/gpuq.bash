_gpuq() {
    local i cur prev opts cmd
    COMPREPLY=()
    if [[ "${BASH_VERSINFO[0]}" -ge 4 ]]; then
        cur="$2"
    else
        cur="${COMP_WORDS[COMP_CWORD]}"
    fi
    prev="$3"
    cmd=""
    opts=""

    for i in "${COMP_WORDS[@]:0:COMP_CWORD}"
    do
        case "${cmd},${i}" in
            ",$1")
                cmd="gpuq"
                ;;
            gpuq,check-config)
                cmd="gpuq__check__config"
                ;;
            gpuq,daemon)
                cmd="gpuq__daemon"
                ;;
            gpuq,desktop)
                cmd="gpuq__desktop"
                ;;
            gpuq,help)
                cmd="gpuq__help"
                ;;
